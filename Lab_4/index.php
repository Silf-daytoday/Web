// ========== Функция формирования строки таблицы ==========
// Возвращает HTML-код строки таблицы (<tr>...</tr>) с заданным числом колонок
function getTR($data, $cols) {
    // Если строка пустая, не выводим строку
    if (trim($data) === '') {
        return '';
    }
    
    // Разбиваем строку на ячейки
    $cells = explode('*', $data);
    $row = '<tr>';
    
    // Формируем ячейки до требуемого количества колонок
    for ($i = 0; $i < $cols; $i++) {
        if (isset($cells[$i])) {
            $row .= '<td>' . $cells[$i] . '</td>';
        } else {
            $row .= '<td></td>';
        }
    }
    
    $row .= '</tr>';
    return $row;
}

// ========== Функция вывода таблицы ==========
// Выводит таблицу по заданной структуре, если она содержит хотя бы одну непустую строку.
function outTable($structure, $cols, $num) {
    // Разбиваем структуру на строки
    $strings = explode('#', $structure);
    
    // Если массив строк пуст (нет ни одной строки)
    if (count($strings) == 0) {
        echo "<p>В таблице нет строк</p>";
        return;
    }
    
    $datas = ''; // накопленный HTML-код строк
    $hasRows = false; // флаг наличия хотя бы одной непустой строки
    
    for ($i = 0; $i < count($strings); $i++) {
        $rowHtml = getTR($strings[$i], $cols);
        if ($rowHtml !== '') {
            $datas .= $rowHtml;
            $hasRows = true;
        }
    }
    
    // Если нет ни одной строки с ячейками
    if (!$hasRows) {
        echo "<p>В таблице нет строк с ячейками</p>";
        return;
    }
    
    // Вывод заголовка таблицы
    echo "<h2>Таблица №{$num}</h2>";
    
    // Вывод таблицы
    echo '<table border="1" cellpadding="5" cellspacing="0">';
    echo $datas;
    echo '</table>';
}

